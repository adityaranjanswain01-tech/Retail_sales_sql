--create each shift and number of orders (eg morning <=12, afternooon between 12 & 17,evening > 17)
with hourly_sale
as
(select *,
	case
		when extract(hour from sale_time) < 12 then 'Morning'
		when extract(hour from sale_time) between 12 and 17 then 'Afternoon'
		else 'evening'
	end as shift
from retail_sales
)
select 
	shift,
	count(*)as total_orders from hourly_sale
group by shift

