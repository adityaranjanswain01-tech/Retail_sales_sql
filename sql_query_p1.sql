-- CREATING THE TABLE 

DROP TABLE IF EXISTS retail_sales; 
CREATE TABLE retail_sales
		(
		transactions_id INT,
		sale_date DATE,
		sale_time TIME,
		customer_id INT,
		gender VARCHAR(15),
		age INT,
		category VARCHAR(20),
		quantiy INT,
		price_per_unit FLOAT,
		cogs FLOAT,
		total_sale FLOAT
		)	

