--Find the top 3 customers in terms of total spending within each category.
with customer_spending as(select 
	customer_id,
	category,
	round(sum(total_sale)::numeric,2) as total_spent,
	RANK()
OVER(
    PARTITION BY category
    ORDER BY sum(total_sale)
)as spend_rank
from retail_sales
group by 1,2)

select customer_id,category,total_spent,spend_rank
from customer_spending 
where spend_rank <=3
order by 2,4

-- Find the percentage contribution of each category to the overall sales.
SELECT
    category,
    ROUND(SUM(total_sale)::numeric, 2) AS category_sales,
    ROUND((100 * SUM(total_sale) / SUM(SUM(total_sale)) OVER ())::numeric,2
    ) AS pct_of_total
FROM retail_sales
GROUP BY 1
ORDER BY 3 DESC;
-- Find the monthly sales trend and calculate the difference between each
WITH monthly_sales AS (
    SELECT
        DATE_TRUNC('month', sale_date)::date AS month,
        SUM(total_sale) AS monthly_sales
    FROM retail_sales
    GROUP BY 1
)
SELECT
    month,
    ROUND(monthly_sales::numeric, 2) AS monthly_sales,
    ROUND((monthly_sales - LAG(monthly_sales) OVER (ORDER BY month))::numeric, 2)
        AS diff_from_prev_month,
    ROUND(
        (100.0 * (monthly_sales - LAG(monthly_sales) OVER (ORDER BY month))
         / LAG(monthly_sales) OVER (ORDER BY month))::numeric,
        2
    ) AS pct_change
FROM monthly_sales
ORDER BY month;